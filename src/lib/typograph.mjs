// Неразрывные пробелы в коротких текстах сайта (статьи блога, описания в списках ссылок):
//  - между разрядами числа: «1 000», «27 540» не расходятся по строкам;
//  - перед ₽ и %: «990 ₽»;
//  - перед тире: тире не начинает строку;
//  - между числом и месяцем: «31 октября» не рвётся на «31» в конце строки и «октября» в начале следующей;
//  - перед стрелкой: «→», «↗» и «↓» не уходят одни на новую строку.
export const NBSP = ' ';
const MONTHS = 'января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря';

export function glue(text) {
  if (typeof text !== 'string') return text;
  let out = text;
  for (let prev = ''; prev !== out; ) {
    prev = out;
    out = out.replace(/(\d) (\d{3})(?!\d)/g, `$1${NBSP}$2`);
  }
  return out
    .replace(/(\d) ([₽%])/g, `$1${NBSP}$2`)
    .replace(/ —/g, `${NBSP}—`)
    .replace(/ ([→↗↓↑←])/g, `${NBSP}$1`)
    .replace(new RegExp(`(\\d) (${MONTHS})`, 'g'), `$1${NBSP}$2`);
}
