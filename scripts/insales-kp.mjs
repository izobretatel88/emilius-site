  o.push('> Шаблон. Перед первой отправкой — проверка юристом; формулировки договора главнее этого текста.', '');
  o.push('## 1. Результат', '');
  o.push('Интернет-магазин на платформе InSales в аккаунте Заказчика, принимающий заказы с оплатой и доставкой по сценариям раздела 5.', '');
  o.push('## 2. Состав работ', '');
  o.push('| id | Работа | Объём | Результат |', '|---|---|---|---|');
