feat = {f['id']: f for f in reg['features']}
OK = {'yes', 'connection'}
SOFT = {'unknown', 'caution'}

def status_html(st):
    return f'<span class="status {st[0]}"><span aria-hidden="true">{st[1]}</span>{st[2]}</span>'

row_re = re.compile(r'<tr id="(F\d{3})" data-feature data-search="[^"]*" data-different="\w+" data-uncertain="\w+" data-confirmed="\w+">\n(<th scope="row">.*?</th>)\n<td>(.*?)</td><td>(.*?)</td><td class="note">(.*?)</td></tr>(<tr class="mobile-note-row" data-note-for="F\d{3}">.*?</tr>)?', re.S)
cls_re = re.compile(r'<span class="status (\w+)"><span aria-hidden="true">[^<]*</span>([^<]*)</span>')

changed = 0
def repl(m):
    global changed
    fid, th, ins, kit, note, mob = m.groups()
    if fid not in U:
        return m.group(0)
    st, text = U[fid]
    f = feat[fid]
    old_note = f['note']
    if text.startswith('+'):
        new_note = (old_note + ' ' + text[1:]).strip()
    elif text == '' and st is not KEEP:
        # строку подтвердил KIT без оговорок; старые догадки про KIT убираем
        new_note = '' if 'KIT' in old_note else old_note
    else:
        new_note = text
    if st is not KEEP:
        kit = status_html(st) + SRC
        f['kit'] = st[3]
    else:
        kit = re.sub(r'<a class="source".*?</a>', '', kit) + SRC
    f['kit_source'] = 'K58'
    f['note'] = new_note
    i_cls, i_lab = cls_re.search(ins).groups()
    k_cls, k_lab = cls_re.search(kit).groups()
    different = i_lab != k_lab
    uncertain = i_cls in SOFT or k_cls in SOFT
    confirmed = i_cls in OK and k_cls in OK
    name = re.search(r'aria-label="Ссылка на функцию: ([^"]*)"', th).group(1)
    search = f'{fid} {f["group"]} {name} {new_note} {i_lab} {k_lab}'
    note_html = escape(new_note, quote=False) if new_note else '<span class="muted"><span class="sr-only">Дополнительных оговорок нет</span><span aria-hidden="true">—</span></span>'
    out = (f'<tr id="{fid}" data-feature data-search="{escape(search)}" data-different="{str(different).lower()}" '
           f'data-uncertain="{str(uncertain).lower()}" data-confirmed="{str(confirmed).lower()}">\n{th}\n'
           f'<td>{ins}</td><td>{kit}</td><td class="note">{note_html}</td></tr>')
    if new_note:
        out += (f'<tr class="mobile-note-row" data-note-for="{fid}"><td colspan="4"><details><summary>Оговорки и различия</summary>'
                f'<p>{escape(new_note, quote=False)}</p></details></td></tr>')
    changed += 1
    return out

h = row_re.sub(repl, h)
