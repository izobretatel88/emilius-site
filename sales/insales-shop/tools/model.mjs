// ── Расчёт ──────────────────────────────────────────────────────────────────
export function estimate(input) {
  const b = { ...defaults(), ...input };
  const lines = [];
  for (const w of WORKS) {
    if (w.m === 'M0') continue; // Этап 0 — отдельная фиксированная цена, см. STAGE0
    const on = w.base || (w.when ? w.when(b) : false);
    if (!on) continue;
    const h = typeof w.hours === 'function' ? w.hours(b) : w.hours;
    lines.push({ ...w, h });
  }
  // Круг правок — 8 % от остальных часов
  const raw = lines.reduce((s, l) => s + l.h, 0);
  const fix = lines.find((l) => l.id === 'M16.2');
  if (fix) fix.h = Math.round(raw * 0.08 * 2) / 2;
  // Если материалы не готовы — +15 % на ожидание и переделки (по опыту — главный источник перерасхода)
  const readinessK = b.ready ? 0 : 0.15;

  const byRole = {};
  let hours = 0, cost = 0, min = 0, max = 0;
  for (const l of lines) {
    l.h = Math.round(l.h * 4) / 4;
    const rate = ROLES[l.role].rate;
    l.cost = l.h * rate;
    hours += l.h;
    cost += l.cost;
    min += l.h * l.spread[0] * rate;
    max += l.h * l.spread[1] * rate;
    byRole[l.role] = (byRole[l.role] || 0) + l.h;
  }
  const urgK = URGENCY[Math.min(3, n(b.urgency))];
  const riskK = RISK[riskLevel(b)];
  const k = 1 + urgK + riskK + readinessK;
  const disc = (VOLUME_DISCOUNT.find(([h]) => hours >= h) || [0, 0])[1];
  const total = cost * k * (1 - disc);
  const round = (x) => Math.round(x / 1000) * 1000;
  // Срок: 4 продуктивных часа исполнителя в день, роли параллелятся частично,
  // плюс 5 рабочих дней на ожидание клиента (доступы, банк, согласования).
  const days = Math.ceil((hours / 4) * 0.75 + 5);
  return {
    brief: b, lines, hours, byRole, cost, k, urgK, riskK, readinessK, risk: riskLevel(b), disc,
    total: round(total), min: round(min * k * (1 - disc)), max: round(max * k * (1 - disc)),
    weeks: Math.ceil(days / 5), custom: b.design === 'custom',
    fixCorridor: [round(total * 0.7), round(total * 1.3)],
  };
}

